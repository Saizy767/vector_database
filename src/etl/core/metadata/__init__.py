"""
Модуль для управления и генерации метаданных в VectorDB ETL пайплайне.

Предоставляет инструменты для создания структурированных метаданных для каждого чанка текста:
- metadata_builder.py: Основной генератор метаданных
- base.py: Абстрактный базовый класс для генераторов метаданных

Структура метаданных:
- chunk_id: Уникальный идентификатор чанка (UUID)
- chunk_index: Порядковый номер чанка в исходном тексте
- total_chunks: Общее количество чанков в исходном тексте
- source_id: Идентификатор источника данных
- data: Пользовательские метаданные (автор, название, глава и т.д.)

Ключевые возможности:
- Валидация метаданных через Pydantic модели
- Маппинг полей из исходных данных в стандартные поля
- Генерация уникальных идентификаторов для каждого чанка
- Поддержка вложенных структур данных

Использование:
from etl.core.metadata import MetadataBuilder

builder = MetadataBuilder(field_mapping={'author': 'doc_author'})
metadata = builder.build(
    row_data={'author': 'Толстой', 'title': 'Война и мир'},
    chunk_index=0,
    total_chunks=10,
    source_id='book_001'
)

Метаданные критически важны для фильтрации результатов поиска и предоставления контекста в ответах.
"""

